-- School & Exam Guide setup. Non-destructive: does not alter or delete public.jobs rows.
create table if not exists public.school_articles (
 id bigint generated by default as identity primary key,
 slug text not null unique,
 title text not null,
 excerpt text not null,
 content text not null,
 grade text not null,
 subject text not null,
 status text not null default 'draft' check(status in ('draft','published')),
 published_at timestamptz,
 created_at timestamptz not null default now()
);
alter table public.school_articles enable row level security;
grant select on public.school_articles to anon, authenticated;
drop policy if exists "Public read published school articles" on public.school_articles;
create policy "Public read published school articles" on public.school_articles
 for select to anon, authenticated using (status = 'published');
