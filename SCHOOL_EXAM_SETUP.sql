-- Education News Feed migration. Safe/idempotent: does not delete jobs or existing study articles.
create table if not exists public.school_articles (
 id bigint generated by default as identity primary key,
 slug text not null unique, title text not null, excerpt text not null, content text not null,
 grade text not null default 'All Students', subject text not null default 'Education',
 status text not null default 'draft' check(status in ('draft','published')),
 published_at timestamptz, created_at timestamptz not null default now()
);

alter table public.school_articles add column if not exists article_type text not null default 'study_guide';
alter table public.school_articles add column if not exists source_url text;
alter table public.school_articles add column if not exists source_name text;
alter table public.school_articles add column if not exists original_published_at timestamptz;
alter table public.school_articles add column if not exists updated_at timestamptz not null default now();

alter table public.school_articles enable row level security;
grant select on public.school_articles to anon, authenticated;
drop policy if exists "Public read published school articles" on public.school_articles;
create policy "Public read published school articles" on public.school_articles
 for select to anon, authenticated using (status = 'published');

-- Keep the table public-read-only through anon/authenticated policies. The GitHub Actions
-- workflow uses SUPABASE_SERVICE_ROLE_KEY as a GitHub Actions secret; never expose it in JS.
