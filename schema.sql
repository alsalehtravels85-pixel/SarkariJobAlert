-- SarkariJobAlert database setup. Safe to run more than once.
-- Run in Supabase SQL Editor. Never put service-role keys in browser files.

create table if not exists public.jobs (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  department text,
  category text not null default 'Latest Jobs',
  vacancies text,
  notification_date date,
  last_date date,
  dob_from date,
  dob_to date,
  qualification text,
  fees text,
  age_limit text,
  selection_process text,
  notification_url text,
  apply_url text,
  description text,
  source_name text,
  source_url text,
  status text not null default 'draft',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Add fields to older installations without deleting existing records.
alter table public.jobs add column if not exists notification_date date;
alter table public.jobs add column if not exists dob_from date;
alter table public.jobs add column if not exists dob_to date;
alter table public.jobs add column if not exists source_name text;
alter table public.jobs add column if not exists source_url text;
alter table public.jobs add column if not exists updated_at timestamptz not null default now();

create index if not exists jobs_status_created_idx
  on public.jobs (status, created_at desc);
create index if not exists jobs_category_status_idx
  on public.jobs (category, status);
-- URL duplicates are handled by the fetcher; a unique index is intentionally not
-- forced here because older databases may already contain duplicate URLs.

alter table public.jobs enable row level security;

drop policy if exists "Public can read published jobs" on public.jobs;
create policy "Public can read published jobs"
on public.jobs for select to anon, authenticated
using (status = 'published');

drop policy if exists "Admin can read all jobs" on public.jobs;
create policy "Admin can read all jobs"
on public.jobs for select to authenticated
using ((auth.jwt() ->> 'email') = 'alsalehtravels85@gmail.com');

drop policy if exists "Admin can insert jobs" on public.jobs;
create policy "Admin can insert jobs"
on public.jobs for insert to authenticated
with check (
  (auth.jwt() ->> 'email') = 'alsalehtravels85@gmail.com'
  and (created_by is null or created_by = auth.uid())
);

drop policy if exists "Admin can update jobs" on public.jobs;
create policy "Admin can update jobs"
on public.jobs for update to authenticated
using ((auth.jwt() ->> 'email') = 'alsalehtravels85@gmail.com')
with check ((auth.jwt() ->> 'email') = 'alsalehtravels85@gmail.com');

drop policy if exists "Admin can delete jobs" on public.jobs;
create policy "Admin can delete jobs"
on public.jobs for delete to authenticated
using ((auth.jwt() ->> 'email') = 'alsalehtravels85@gmail.com');

-- Push subscription token registry.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  token text not null unique,
  user_agent text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
drop policy if exists "Visitors can subscribe to push" on public.push_subscriptions;
create policy "Visitors can subscribe to push"
on public.push_subscriptions for insert to anon, authenticated
with check (length(token) > 20);
drop policy if exists "Visitors can refresh their push token" on public.push_subscriptions;
create policy "Visitors can refresh their push token"
on public.push_subscriptions for update to anon, authenticated
using (false) with check (false);

