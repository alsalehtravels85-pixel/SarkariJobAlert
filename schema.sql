-- Run in Supabase SQL Editor.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  token text not null unique,
  user_agent text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;

-- Visitors can subscribe (insert/upsert) but cannot read tokens.
drop policy if exists "Visitors can subscribe to push" on public.push_subscriptions;
create policy "Visitors can subscribe to push"
on public.push_subscriptions for insert
to anon, authenticated
with check (length(token) > 20);

drop policy if exists "Visitors can refresh their push token" on public.push_subscriptions;
create policy "Visitors can refresh their push token"
on public.push_subscriptions for update
to anon, authenticated
using (false)
with check (false);

-- IMPORTANT: This is a token registry. Only a trusted server using the Supabase
-- service-role key should read, disable, or delete tokens. Never expose service-role key.
